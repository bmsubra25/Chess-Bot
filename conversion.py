def represent(board: Board):
  matrix = torch.zeros((18,8,8))
  map = board.piece_map()
  for key in map:
    piece_type = map[key].piece_type
    piece_color = map[key].color
    suffix = piece_labels[piece_type]
    prefix = "w" if piece_color else "b"
    channel = channels[prefix + suffix]
    row = 7 - key//8
    col = key % 8
    matrix[channel,row,col] = 1
  if board.turn == chess.WHITE:
        matrix[channels["stm"], :, :] = 1
  if board.has_kingside_castling_rights(chess.WHITE):
        matrix[channels["wkc"], :, :] = 1
  if board.has_queenside_castling_rights(chess.WHITE):
        matrix[channels["wqc"], :, :] = 1
  if board.has_kingside_castling_rights(chess.BLACK):
        matrix[channels["bkc"], :, :] = 1
  if board.has_queenside_castling_rights(chess.BLACK):
        matrix[channels["bqc"], :, :] = 1
  if board.ep_square is not None:
        ep_row = 7 - (board.ep_square // 8)
        ep_col = board.ep_square % 8
        matrix[channels["ep"], ep_row, ep_col] = 1
  move_matrix = torch.zeros((64,64))
  return matrix
def generate_input(games):
  X = []
  y = []
  for game in games:
    board = game.board()
    moves = list(game.mainline_moves())
    result = game.headers["Result"]
    if result not in ["1-0", "0-1", "1/2-1/2"]:
        continue
    if result == "1-0":
        label = 1
    elif result == "0-1":
        label = -1
    else:
        label = 0
    k = random.randint(1, len(moves))
    moves = moves[0:k]
    for move_index,move in enumerate(moves):
      board.push(move)
      if move_index > 4:
        X.append(represent(board))
        y.append(label)
    return X,y

